import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync, mkdtempSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSkin, emit, readSkin, SKIP_REASON, SKIN_REL, GENERATED_REL } from '../scripts/sync-house-tokens.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..', '..');
const generatedPath = join(here, '..', GENERATED_REL);

// Colour tokens whose value is not a #rrggbb literal: shadows and the scrim carry alpha, and these
// roles are var() aliases of other tokens. Every other colour token must be #rrggbb.
const NON_LITERAL_COLOUR = new Set([
  '--shadow-card', '--shadow-raise', '--shadow-pop', '--scrim',
  '--row-hover', '--nav-ink', '--nav-on-bg', '--input-fill', '--input-edge', '--block-bg', '--divider',
]);

function parseGenerated(css) {
  const body = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const decls = (s) => [...s.matchAll(/(--[\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]);
  const light = body.match(/^:root \{([^}]*)\}/m);
  const media = body.match(/@media \(prefers-color-scheme: dark\) \{\s*:root:not\(\[data-theme="light"\]\) \{([^}]*)\}\s*\}/);
  const attr = body.match(/^:root\[data-theme="dark"\] \{([^}]*)\}/m);
  assert.ok(light && media && attr, 'generated file has the three blocks');
  return { light: decls(light[1]), darkMedia: decls(media[1]), darkAttr: decls(attr[1]) };
}

const generated = readFileSync(generatedPath, 'utf8');
const got = parseGenerated(generated);
const skinPath = join(repoRoot, SKIN_REL);

function agreement(skinPathArg) {
  const skinCss = readSkin(skinPathArg);
  if (skinCss === null) return { skipped: SKIP_REASON };
  const want = parseSkin(skinCss);
  assert.deepEqual(got.light, want.light, 'light block');
  assert.deepEqual(got.darkMedia, want.darkMedia, 'dark media block');
  assert.deepEqual(got.darkAttr, want.darkAttr, 'dark attribute block');
  const sha = createHash('sha256').update(skinCss).digest('hex');
  assert.match(generated, new RegExp(`sha256:${sha} `), 'header sha matches the skin file');
  return { skipped: null };
}

test('every skin token is in the kms copy with the same value, in each block, and no extras',
  { skip: readSkin(skinPath) === null ? SKIP_REASON : false },
  () => assert.equal(agreement(skinPath).skipped, null));

test('the agreement check is skipped, with its reason, when the skin is absent', () => {
  const absent = join(mkdtempSync(join(tmpdir(), 'kms-noskin-')), 'house.css');
  assert.deepEqual(agreement(absent), { skipped: 'house skin not present (kms vendored alone)' });
});

test('the dark blocks hold identical names and values; their names are all in the light block', () => {
  assert.deepEqual(got.darkMedia, got.darkAttr);
  const light = new Set(got.light.map(([n]) => n));
  for (const [n] of got.darkAttr) assert.ok(light.has(n), `${n} is also in the light block`);
  assert.ok(got.darkAttr.length > 0);
});

test('every colour token is #rrggbb, except the named non-literal set', () => {
  for (const block of [got.light, got.darkMedia, got.darkAttr]) {
    for (const [n, v] of block) {
      if (NON_LITERAL_COLOUR.has(n)) continue;
      if (v.startsWith('#') || /^(rgba?|hsla?|color-mix)\(/.test(v)) {
        assert.match(v, /^#[0-9a-f]{6}$/, `${n}: ${v}`);
      }
    }
  }
  // the exception set must be real: those that are present are not hex literals
  for (const [n, v] of got.light) if (NON_LITERAL_COLOUR.has(n)) assert.doesNotMatch(v, /^#/, n);
});

test('the generated file says GENERATED and names the relative source path, no absolute path', () => {
  const header = generated.split('\n')[0];
  assert.match(header, /^\/\* GENERATED by scripts\/sync-house-tokens\.mjs from packages\/admin\/app\/src\/design\/skins\/house\.css sha256:[0-9a-f]{64} — do not edit\. \*\/$/);
  assert.doesNotMatch(generated, /\/Users\/|\/private\/|~\/|\/home\//);
});

test('emit reproduces the committed file byte for byte', () => {
  if (readSkin(skinPath) === null) return;
  const skinCss = readFileSync(skinPath, 'utf8');
  const sha256 = createHash('sha256').update(skinCss).digest('hex');
  assert.equal(emit(parseSkin(skinCss), { sourcePath: SKIN_REL, sha256 }), generated);
});

test('parseSkin throws on a sheet with two light blocks, or with a block missing', () => {
  const light = ':root, :root[data-skin="house"] { --a: #111111; }';
  const dark = '@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]), :root[data-skin="house"]:not([data-theme="light"]) { --a: #222222; } }';
  const attr = ':root[data-theme="dark"], :root[data-skin="house"][data-theme="dark"] { --a: #222222; }';
  assert.deepEqual(parseSkin(`${light}\n${dark}\n${attr}`).light, [['--a', '#111111']]);
  assert.throws(() => parseSkin(`${light}\n${light}\n${dark}\n${attr}`), /light/);
  assert.throws(() => parseSkin(`${light}\n${dark}`), /darkAttr/);
  assert.throws(() => parseSkin(`${dark}\n${attr}`), /light/);
});
