#!/usr/bin/env node
// Generates src/house/house-tokens.css from the DAO-OS house skin. Run by hand:
//   node packages/org-os-kms/scripts/sync-house-tokens.mjs
// The test (test/house-tokens.test.mjs) checks the committed copy still agrees with the skin.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SKIN_REL = 'packages/admin/app/src/design/skins/house.css';
export const GENERATED_REL = 'src/house/house-tokens.css';
export const SKIP_REASON = 'house skin not present (kms vendored alone)';

// Reads the skin, or returns null when it is absent (kms vendored alone).
export function readSkin(skinPath) {
  return existsSync(skinPath) ? readFileSync(skinPath, 'utf8') : null;
}

function declarations(body) {
  return [...body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]);
}

// Splits a sheet into rules; an @media rule carries its inner rules.
function rules(css) {
  const out = [];
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    const body = css.slice(open + 1, j - 1);
    out.push(head.startsWith('@media') ? { media: head, inner: rules(body) } : { selectors: head.split(',').map((s) => s.trim()), body });
    i = j;
  }
  return out;
}

const DARK_MEDIA = /^@media\s*\(\s*prefers-color-scheme:\s*dark\s*\)$/;

export function parseSkin(css) {
  const all = rules(css.replace(/\/\*[\s\S]*?\*\//g, ''));
  const top = all.filter((r) => r.selectors);
  const dark = all.filter((r) => r.media && DARK_MEDIA.test(r.media)).flatMap((r) => r.inner);
  const found = {
    light: top.filter((r) => r.selectors.includes(':root[data-skin="house"]') && !r.selectors.some((s) => s.includes('data-theme'))),
    darkMedia: dark.filter((r) => r.selectors.some((s) => s.includes('[data-skin="house"]'))),
    darkAttr: top.filter((r) => r.selectors.includes(':root[data-theme="dark"]')),
  };
  const result = {};
  for (const [key, list] of Object.entries(found)) {
    if (list.length !== 1) throw new Error(`house skin: expected exactly one ${key} block, found ${list.length}`);
    result[key] = declarations(list[0].body);
  }
  return result;
}

export function emit(parsed, { sourcePath, sha256 }) {
  const lines = (decls) => decls.map(([n, v]) => `${n}: ${v};`);
  const block = (sel, decls, pad) => [`${pad}${sel} {`, ...lines(decls).map((l) => `${pad}  ${l}`), `${pad}}`];
  return [
    `/* GENERATED by scripts/sync-house-tokens.mjs from ${sourcePath} sha256:${sha256} — do not edit. */`,
    ...block(':root', parsed.light, ''),
    '@media (prefers-color-scheme: dark) {',
    ...block(':root:not([data-theme="light"])', parsed.darkMedia, '  '),
    '}',
    ...block(':root[data-theme="dark"]', parsed.darkAttr, ''),
    '',
  ].join('\n');
}

export function generate({ skinPath, outPath }) {
  const css = readFileSync(skinPath, 'utf8');
  const sha256 = createHash('sha256').update(css).digest('hex');
  const text = emit(parseSkin(css), { sourcePath: SKIN_REL, sha256 });
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, text);
  return text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const here = dirname(fileURLToPath(import.meta.url));
  generate({ skinPath: join(here, '..', '..', '..', SKIN_REL), outPath: join(here, '..', GENERATED_REL) });
  console.log(`wrote ${GENERATED_REL}`);
}
