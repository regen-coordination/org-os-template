// src/render-map-html.mjs
// `render map html` — the vault artifact, the steward's copy (spec §5.1, §6, §8): ONE self-contained
// HTML in the house. The artifact bar (the instance's name, "Federation map · generated <date time>",
// List · Map and Fit), then <federation-map data-surface="vault"> holding the map pre-drawn in its
// light DOM — nodes as HTML, edges as one inline SVG, the caption and the list twin, all computed here —
// and the map data; then the component bundle, inlined. Without JavaScript the page is complete (the
// map and its list twin); the script only adds selection, keys, the List · Map toggle, Fit and zoom.
// Nothing is fetched: one <style> (house tokens, CSS, the map's CSS, the fonts inline), one sprite.
// The links index (federation-links.md) uses the vault surface (obsidian:// links). In map.json v1 a node's link
// is its `portal` key (source-systems' `portal_web` / `portal_vault`), kept as data until map.json v2 (PF-R120).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildMap } from './map.mjs';
import { loadKmsConfig } from './config.mjs';
import { page, artBar, esc } from './house/html.mjs';
import { icon } from './house/icons.mjs';
import { renderStaticMap, nodeView, ICONS_USED, mapCss } from './house/fedmap.mjs';

const DEFAULT_BUNDLE = join(
  dirname(fileURLToPath(import.meta.url)),
  '..', '..', 'org-os-federation-map', 'dist', 'federation-map.iife.js',
);

// The element's id: the bar's controls name it in aria-controls (the component's #controls()).
const MAP_ID = 'fedmap';

// What this page adds to the house CSS (tokens only). The element is a block; until the component is
// defined (no JavaScript, or a viewer that strips scripts) the List · Map and Fit controls are hidden —
// they would do nothing, and both views already show: the map, then its list twin (R-19). The map sits
// close under the bar, as the gallery draws it (§02).
const PAGE_CSS = `
federation-map { display: block; min-width: 0; }
.art-body.art-map { padding: var(--sp-8); gap: var(--sp-8); }
body:has(federation-map:not(:defined)) .art-bar .tools { display: none; }
.art-body > .note code { font-size: var(--fs-code); color: var(--ink); }
`;

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const two = (n) => String(n).padStart(2, '0');
// "29 Oct 2026 12:00 UTC" — the clock this page was generated by, in UTC (the same file on any machine)
function generatedAt(iso) {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return esc(iso);
  return `${d.getUTCDate()} ${MONTHS[d.getUTCMonth()]} ${d.getUTCFullYear()} ${two(d.getUTCHours())}:${two(d.getUTCMinutes())} UTC`;
}

// render.fonts from kms.yaml, read leniently: the map renders without kms.yaml (spec §6), and then
// with the house fonts.
function fontsMode(dir) {
  try { return loadKmsConfig(dir).render.fonts === 'system' ? 'system' : 'house'; } catch { return 'house'; }
}

const list = (xs) => (xs.length <= 1 ? xs.join('') : `${xs.slice(0, -1).join(', ')} and ${xs[xs.length - 1]}`);

// note (L4 §7.4) with a command in it: html, built from escaped parts
const noteHtml = (html, tone = '') => `<p class="note${tone ? ` ${tone}` : ''}">${icon('info')}<span>${html}</span></p>`;

export function renderMapHtml({ dir = '.', out = 'renders/federation-map.html', bundlePath = DEFAULT_BUNDLE, now = new Date().toISOString() } = {}) {
  const map = buildMap({ dir, surface: 'vault', now });
  const bundle = readFileSync(bundlePath, 'utf8');
  // Inline content must not end its <script> element early. JSON: `<` only occurs inside
  // strings, where \u003c means the same thing, so escape every one (this also rules out
  // `<!--`, which can stop the real closing tag from closing).
  const data = JSON.stringify(map).replace(/</g, '\\u003c');

  const tools = `<span class="seg" role="group" aria-label="View">`
    + `<button type="button" data-fm-view="list" aria-controls="${MAP_ID}" aria-pressed="false">${icon('list')}List</button>`
    + `<button type="button" data-fm-view="map" aria-controls="${MAP_ID}" aria-pressed="true">${icon('map')}Map</button></span>`
    + `<button class="btn icon" type="button" data-fm-fit aria-controls="${MAP_ID}" aria-label="Fit to view">${icon('fit')}</button>`;
  const bar = artBar({
    name: map.self.name,
    sub: `Federation map<span class="gen"> · generated <time datetime="${esc(now)}">${generatedAt(now)}</time></span>`,
    tools,
  });

  // the steward's notes under the map (spec §6): no peers yet; a peer whose frontier was never read
  const notes = [];
  if (!map.nodes.length) {
    notes.push(noteHtml('No peers yet. Add one with <code>org-os-kms federate add --card &lt;file&gt;</code>.', 'empty'));
  }
  const never = map.nodes.filter((n) => nodeView(n, map, { surface: 'vault', now }).states.includes('never'))
    .map((n) => esc(n.name ?? n.id)).sort((a, b) => a.localeCompare(b));
  if (never.length) {
    notes.push(noteHtml(`${list(never)} ${never.length === 1 ? 'has' : 'have'} no frontier yet. `
      + `Read ${never.length === 1 ? 'it' : 'them'} with <code>org-os-kms federate frontier</code>.`));
  }

  const body = `<div class="art">${bar}<main class="art-body art-map">`
    + `<federation-map id="${MAP_ID}" data-surface="vault">${renderStaticMap(map, { surface: 'vault', now })}`
    + `<script type="application/json">${data}</script></federation-map>`
    + `${notes.join('')}</main></div>`;
  // The bundle goes in through page(), which escapes only `</script` (any case), as `<\/script`: in a
  // string, template or regex literal `\/` reads as `/`, so the code means the same. Escaping every
  // `</` broke the real bundle: its HTML escaper's regex `/</g` became `/<\/g…`, whose closing slash
  // was now escaped — a SyntaxError, and a blank page.
  const html = page({
    title: `${map.self.name} — federation map`,
    groups: ['base', 'atoms', 'rows', 'art'],
    extraCss: [mapCss(), PAGE_CSS],
    fonts: fontsMode(dir),
    icons: [...ICONS_USED, 'list', 'map', 'fit', 'info'],
    body,
    script: bundle,
  });
  const outPath = join(dir, out);
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, html);
  return { ok: true, report: { wrote: outPath, nodes: map.nodes.length, edges: map.edges.length } };
}

const KIND_HEADINGS = [['instance', 'Instances'], ['frontier', 'One hop beyond'], ['source', 'Sources'], ['ecosystem', 'Ecosystems']];

/** The links index: one line a node, each a deep link into the vault artifact, grouped by kind. */
export function renderLinksIndex({ dir = '.', out = 'renders/federation-links.md', now = new Date().toISOString() } = {}) {
  const map = buildMap({ dir, surface: 'vault', now });
  const lines = [
    `# Federation links — ${map.self.name}`,
    '',
    `> Links between the internal note graph and [the federation map](federation-map.html). Generated ${now} — regenerate with \`org-os-kms render map html\`. Link to these anchors from any note.`,
  ];
  for (const [kind, heading] of KIND_HEADINGS) {
    const group = map.nodes.filter((n) => n.kind === kind).sort((a, b) => a.id.localeCompare(b.id));
    if (!group.length) continue;
    lines.push('', `## ${heading}`, '');
    for (const n of group) {
      const extras = [n.type, n.live === false && n.kind === 'instance' ? 'not reached' : null].filter(Boolean).join(' · ');
      lines.push(`- [${n.name || n.id}](federation-map.html#node=${encodeURIComponent(n.id)})${extras ? ` — ${extras}` : ''}`);
    }
  }
  const outPath = join(dir, out);
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, lines.join('\n') + '\n');
  return { ok: true, report: { wrote: outPath, links: map.nodes.length } };
}
