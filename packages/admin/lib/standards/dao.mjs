// packages/admin/lib/standards/dao.mjs
//
// dao.json (the daoURI document), members.json, governance.md and attestation-issuers.json (lane L8, addendum §5.1,
// §5.2, §5.6, §5.9). Builders read the public projection only. Pure; relative imports only (vendored into instances).
import { describeRule } from '../rules.mjs'
import { entityType, memberUri, wellKnown } from './ids.mjs'

const DAOSTAR_HTTP = 'http://www.daostar.org/schemas'
const DAOSTAR_HTTPS = 'https://www.daostar.org/schemas'

/**
 * The generator's mark on dao.json (L8-C18). The instance doctor reads it to tell L8 output from 0.6 output: an
 * instance whose dao.json carries it was generated by this builder, so its members.json, proposals.json … say nothing
 * about what 0.6 published. Fixed bytes: no version, no date, no path, so the git copy stays deterministic.
 */
export const GENERATOR_MARK_KEY = 'x-org-os'
export const GENERATOR_MARK = Object.freeze({ generator: 'org-os standards (L8)' })

/**
 * Does a parsed dao.json carry the generator's mark? Any object under the key with a non-empty `generator` counts,
 * so a later wording of the mark still reads as generated output (0.6 never wrote the key).
 * @param {unknown} doc @returns {boolean}
 */
export function hasGeneratorMark(doc) {
  if (doc === null || typeof doc !== 'object' || Array.isArray(doc)) return false
  const mark = /** @type {Record<string, unknown>} */ (doc)[GENERATOR_MARK_KEY]
  if (mark === null || typeof mark !== 'object' || Array.isArray(mark)) return false
  const generator = /** @type {Record<string, unknown>} */ (mark).generator
  return typeof generator === 'string' && generator.trim() !== ''
}

/** @param {unknown} v @returns {string | null} a non-empty string, else null */
const text = v => (typeof v === 'string' && v.trim() !== '' ? v : null)

/**
 * `present`: the output files that exist this run; a URI key is written only for a present file.
 * @param {import('./project.mjs').PublicInput} pub @param {Set<string>} present @returns {Record<string, unknown>}
 */
export function daoDoc(pub, present) {
  const identity = /** @type {Record<string, unknown>} */ (pub.identity)
  const description = text(identity.short_description) ?? text(identity.description)
  /** @type {Record<string, unknown>} */
  const doc = {
    '@context': DAOSTAR_HTTP,
    type: entityType(String(identity.type)),
    name: identity.name,
    ...(description ? { description } : {}),
    membersURI: wellKnown(pub.origin, 'members.json'),
    proposalsURI: wellKnown(pub.origin, 'proposals.json'),
    activityLogURI: wellKnown(pub.origin, 'activities.json'),
    governanceURI: wellKnown(pub.origin, 'governance.md'),
    contractsURI: wellKnown(pub.origin, 'contracts.json'),
  }
  if (present.has('grant-pools.json')) doc.grantPoolsURI = wellKnown(pub.origin, 'grant-pools.json')
  if (present.has('attestation-issuers.json')) doc.attestationIssuersURI = wellKnown(pub.origin, 'attestation-issuers.json')
  doc.meetingsURI = wellKnown(pub.origin, 'meetings.json')
  doc.financesURI = wellKnown(pub.origin, 'finances.json')
  doc[GENERATOR_MARK_KEY] = { ...GENERATOR_MARK }
  return doc
}

/** L8-C6, Q57: public person/organization members, active or no status, `{ id }` only; no hat wearers. A member whose
 * `kind` or `status` a field rule withholds is left out: its absence from the view is not "person" or "active" (M3).
 * @param {import('./project.mjs').PublicInput} pub @returns {Record<string, unknown>} */
export function membersDoc(pub) {
  const members = pub.members
    .filter(({ record, withheld }) => {
      if (Array.isArray(withheld) && (withheld.includes('kind') || withheld.includes('status'))) return false
      const kind = record.kind === undefined || record.kind === null ? 'person' : record.kind
      const status = record.status === undefined || record.status === null ? 'active' : record.status
      return (kind === 'person' || kind === 'organization') && status === 'active'
    })
    .map(({ id }) => ({ id: memberUri(id, pub.origin) }))
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
  return { '@context': DAOSTAR_HTTPS, type: entityType(String(pub.identity.type)), members }
}

/** @param {import('./project.mjs').PublicInput} pub @returns {string} */
export function governanceMd(pub) {
  const name = String(pub.identity.name)
  if (pub.governance === null) return `How ${name} decides is not public.\n`
  const lines = [`# How ${name} decides`, '']
  const prose = text(pub.governance.description)
  if (prose) lines.push(prose.trim(), '')
  for (const rule of pub.governance.rules) {
    const label = text(rule.id)
    lines.push(`- ${label ? `${label}: ` : ''}${describeRule(/** @type {any} */ (rule))}`)
  }
  return lines.join('\n') + '\n'
}

/** @param {import('./project.mjs').PublicInput} pub @returns {Record<string, unknown> | null} null: no issuers named */
export function issuersDoc(pub) {
  const named = pub.identity.attestationIssuers
  if (!Array.isArray(named)) return null
  const issuers = named
    .filter(i => i && text(i.name) && text(i.issuer))
    .map(i => ({ type: 'AttestationIssuer', name: i.name, issuer: i.issuer }))
    .sort((a, b) => (a.issuer < b.issuer ? -1 : a.issuer > b.issuer ? 1 : 0))
  return issuers.length === 0 ? null : { '@context': DAOSTAR_HTTP, attestationIssuers: issuers }
}
