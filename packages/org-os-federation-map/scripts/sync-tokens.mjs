#!/usr/bin/env node
// Generates src/house-tokens.mjs: the house tokens map.css uses, as a `:host` block for the
// <federation-map> shadow root (spec §5.2, P-5). The component adds it only when the page has no
// house tokens of its own (no `--paper`), so a house page's values always win.
//
// The values come from kms's generated copy of the house skin (packages/org-os-kms/src/house/
// house-tokens.css), read by sibling path. Run by hand after either file changes:
//   node packages/org-os-federation-map/scripts/sync-tokens.mjs
// test/tokens.test.mjs checks the committed copy still agrees with both.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const KMS_TOKENS_REL = 'packages/org-os-kms/src/house/house-tokens.css';
export const KMS_TOKENS = join(here, '..', '..', 'org-os-kms', 'src', 'house', 'house-tokens.css');
export const MAP_CSS_PATH = join(here, '..', 'src', 'map.css');
export const OUT = join(here, '..', 'src', 'house-tokens.mjs');

// The three old theme properties, read for one release as aliases of the house tokens (spec §5.2).
export const ALIASES = Object.freeze({ '--sunken': '--fedmap-bg', '--ink': '--fedmap-text', '--sans': '--fedmap-font' });

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '');

// Every custom property a stylesheet reads with var(), in first-use order.
export function tokensUsed(css) {
  return [...new Set([...stripComments(css).matchAll(/var\(\s*(--[\w-]+)/g)].map((m) => m[1]))];
}

function decls(body) {
  return new Map([...body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
}

// The body of the first rule whose selector is `selector`, searched from `from`.
function ruleBody(css, selector, from = 0) {
  const at = css.indexOf(`${selector} {`, from);
  if (at < 0) return null;
  const open = css.indexOf('{', at);
  return { body: css.slice(open + 1, css.indexOf('}', open)), at };
}

// kms's house-tokens.css → { light: Map, dark: Map } (the dark values are the media block's).
export function parseKmsTokens(css) {
  const c = stripComments(css);
  const light = ruleBody(c, ':root');
  const media = c.indexOf('@media (prefers-color-scheme: dark)');
  const dark = media < 0 ? null : ruleBody(c, ':root:not([data-theme="light"])', media);
  if (!light || !dark) throw new Error('house-tokens.css: expected a :root block and a dark @media block');
  return { light: decls(light.body), dark: decls(dark.body) };
}

// The `:host` blocks, one line each, for exactly the tokens map.css reads (closed over the tokens
// those values read in turn, so a value like `var(--wash)` always resolves).
export function buildTokensCss(kmsCss, mapCss) {
  const { light, dark } = parseKmsTokens(kmsCss);
  const want = tokensUsed(mapCss);
  const names = [];
  const add = (n) => {
    if (names.includes(n) || !light.has(n)) return;
    names.push(n);
    for (const m of tokensUsed(light.get(n))) add(m);
  };
  for (const n of want) add(n);
  names.sort();
  const val = (n, v) => (ALIASES[n] ? `var(${ALIASES[n]}, ${v})` : v);
  const block = (src) => names.filter((n) => src.has(n)).map((n) => `${n}:${val(n, src.get(n))};`).join('');
  return `:host{${block(light)}}@media (prefers-color-scheme: dark){:host{${block(dark)}}}`;
}

export function moduleText(css) {
  return `// GENERATED by scripts/sync-tokens.mjs from ${KMS_TOKENS_REL} — do not edit.\n`
    + '// The house tokens map.css uses, for the shadow root when the page has none (spec §5.2, P-5).\n'
    + `export const HOUSE_TOKENS_CSS = ${JSON.stringify(css)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (!existsSync(KMS_TOKENS)) {
    console.error(`no sibling ${KMS_TOKENS_REL}: run this from the org-os repository`);
    process.exit(2);
  }
  const css = buildTokensCss(readFileSync(KMS_TOKENS, 'utf8'), readFileSync(MAP_CSS_PATH, 'utf8'));
  writeFileSync(OUT, moduleText(css));
  console.log('wrote src/house-tokens.mjs');
}
