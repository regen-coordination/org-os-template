#!/usr/bin/env node
/**
 * clone-manifest.mjs — regenerate tests/clone-manifest.txt.
 *
 * Clones the framework with the reference fixture config
 * (tests/fixtures/instance-config.yaml, --no-git) into a temp directory and
 * writes the sorted list of every file path the clone contains.
 * tests/clone-genesis.test.mjs requires a fresh clone to match it exactly.
 *
 * The clone copies COMMITTED content only, so commit framework changes first,
 * then regenerate, then review the manifest diff: it is exactly what every new
 * organisation will receive.
 *
 * Usage:
 *   npm run clone:manifest            # rewrite tests/clone-manifest.txt
 *   npm run clone:manifest -- --check # exit 1 if the manifest is stale
 */

import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const MANIFEST_PATH = path.join(rootDir, "tests", "clone-manifest.txt");

const HEADER = `# tests/clone-manifest.txt — every path a fresh instance receives.
#
# Generated by \`npm run clone:manifest\` from a clone of the reference fixture
# (tests/fixtures/instance-config.yaml, --no-git). Do not edit by hand.
#
# tests/clone-genesis.test.mjs fails when a fresh clone's path set differs from
# this list in EITHER direction. That friction is deliberate: when you add,
# move or remove a framework file that instances receive, commit it, run
# \`npm run clone:manifest\`, and review this file's diff — it is exactly the
# content every new organisation will inherit. If a line surprises you, fix the
# allow/deny rules in scripts/lib/clone-excludes.mjs instead of accepting it.
`;

function listFiles(dir, rel = "") {
  const out = [];
  for (const entry of readdirSync(path.join(dir, rel), { withFileTypes: true })) {
    const r = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...listFiles(dir, r));
    else out.push(r);
  }
  return out;
}

/** Parse a manifest body into its path list (comments and blanks dropped). */
export function parseManifest(text) {
  return text.split("\n").filter((l) => l && !l.startsWith("#"));
}

/** Sorted path list of a directory, as the manifest records it. */
export function clonePaths(dir) {
  return listFiles(dir).filter((p) => p !== "node_modules").sort();
}

function main() {
  const base = mkdtempSync(path.join(tmpdir(), "clone-manifest-"));
  const dst = path.join(base, "instance");
  try {
    const { NODE_TEST_CONTEXT, NODE_TEST_WORKER_ID, ...env } = process.env;
    const r = spawnSync(
      "node",
      [path.join(rootDir, "scripts", "clone-framework.mjs"), "--target", dst,
        "--config", path.join(rootDir, "tests", "fixtures", "instance-config.yaml"), "--no-git"],
      { encoding: "utf-8", env },
    );
    if (r.status !== 0) {
      console.error(`✗ clone failed:\n${r.stderr}${r.stdout}`);
      process.exit(1);
    }
    const paths = clonePaths(dst);
    const body = HEADER + "\n" + paths.join("\n") + "\n";
    if (process.argv.includes("--check")) {
      const current = parseManifest(readFileSync(MANIFEST_PATH, "utf-8"));
      const same = current.length === paths.length && current.every((p, i) => p === paths[i]);
      console.log(same ? `✓ clone manifest current (${paths.length} paths)` : "✗ clone manifest is stale — run npm run clone:manifest");
      process.exit(same ? 0 : 1);
    }
    writeFileSync(MANIFEST_PATH, body);
    console.log(`✓ wrote tests/clone-manifest.txt (${paths.length} paths)`);
  } finally {
    rmSync(base, { recursive: true, force: true });
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
